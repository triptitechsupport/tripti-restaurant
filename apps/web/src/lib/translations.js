export const getTranslation = (language, key) => {
  if (translations[language] && translations[language][key]) {
    return translations[language][key];
  }
  // Fallback to English if translation doesn't exist
  if (translations['en'] && translations['en'][key]) {
    return translations['en'][key];
  }
  return key; // Fallback to key name itself
};

export const getTranslatedCategoryName = (categoryName, language) => {
  if (!categoryName) return '';
  if (language === 'de') {
    const map = {
      'breakfast': 'Frühstück',
      'appetizers': 'Vorspeisen',
      'main courses': 'Hauptgänge',
      'snacks': 'Snacks',
      'desserts': 'Desserts',
      'sides': 'Beilagen',
      'sides & accompaniments': 'Beilagen',
      'kids menu': 'Kindermenü',
      'beverages': 'Getränke',
      'all': 'Alle Kategorien'
    };
    return map[categoryName.toLowerCase()] || categoryName;
  }
  return categoryName;
};